// 通用工具：HTML 转义、大小/时间格式化、扩展名徽章、SVG 图标

export function esc(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

export function fmtSize(n: number): string {
  if (!n || n <= 0) return "";
  const units = ["B", "KB", "MB", "GB", "TB"];
  let i = 0;
  let v = n;
  while (v >= 1024 && i < units.length - 1) {
    v /= 1024;
    i++;
  }
  return `${v >= 100 || i === 0 ? Math.round(v) : v.toFixed(1)} ${units[i]}`;
}

export function fmtTime(ms: number): string {
  if (!ms) return "";
  const d = new Date(ms);
  const now = new Date();
  const sameDay = d.toDateString() === now.toDateString();
  const pad = (x: number) => String(x).padStart(2, "0");
  if (sameDay) return `${pad(d.getHours())}:${pad(d.getMinutes())}`;
  return `${d.getMonth() + 1}/${d.getDate()} ${pad(d.getHours())}:${pad(d.getMinutes())}`;
}

/** 扩展名徽章（无系统图标时的兜底显示） */
export function extBadge(item: { isDir: boolean; ext: string; name: string }, color: string): string {
  const label = item.isDir
    ? "夹"
    : (item.ext || "文件").replace(/[^a-z0-9]/gi, "").slice(0, 4).toUpperCase() || "文件";
  return `<span class="badge" style="background:${color}22;color:${color};border-color:${color}55">${esc(label)}</span>`;
}

